// Builds the TV display bundle (public/tv/app.js) for old Smart-TV browsers.
//
// LG webOS 3.x TVs run Chromium 38 and webOS 4.x Chromium 53: no ES modules, no arrow functions in
// 38, no async/await, no fetch, no optional chaining, no String#padStart, ... So:
//   1. esbuild bundles src/tv/tv.js + src/shared (TypeScript) into one ES2020 module,
//   2. Babel (preset-env, target Chromium 38) lowers the syntax to ES5 and babel-plugin-polyfill-corejs3
//      injects the core-js polyfills the code actually uses,
//   3. esbuild bundles those polyfills into a single classic (non-module) IIFE script, targeting ES5
//      so any syntax Babel missed fails the build.
// tests/unit/tv-bundle.test.ts re-checks the output parses as ES5.
import { build } from 'esbuild';
import { transformAsync } from '@babel/core';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TV_TARGET_CHROME = '38';
export const TV_BUNDLE = path.join(root, 'public/tv/app.js');

/** Returns the ES5 bundle source. Writes it to public/tv/app.js unless write === false. */
export async function buildTv({ write = true, minify = true } = {}) {
  const modern = await build({
    entryPoints: [path.join(root, 'src/tv/tv.js')],
    bundle: true,
    format: 'esm',
    target: 'es2020',
    write: false,
    logLevel: 'silent',
  });
  const babel = await transformAsync(modern.outputFiles[0].text, {
    babelrc: false,
    configFile: false,
    sourceType: 'module',
    filename: 'tv-bundle.js',
    presets: [
      [
        '@babel/preset-env',
        {
          targets: { chrome: TV_TARGET_CHROME },
          modules: false,
        },
      ],
    ],
    plugins: [
      [
        'babel-plugin-polyfill-corejs3',
        { method: 'usage-global', version: '3.50', targets: { chrome: TV_TARGET_CHROME } },
      ],
    ],
  });
  const legacy = await build({
    stdin: { contents: babel.code, resolveDir: root, sourcefile: 'tv-bundle.js', loader: 'js' },
    bundle: true,
    format: 'iife',
    target: 'es5',
    minify,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
    banner: { js: '/* Masjid Pulse TV - generated by scripts/build-tv.mjs (ES5). Do not edit. */' },
  });
  const code = legacy.outputFiles[0].text;
  if (write) {
    mkdirSync(path.dirname(TV_BUNDLE), { recursive: true });
    writeFileSync(TV_BUNDLE, code);
  }
  return code;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const code = await buildTv();
  console.log(`public/tv/app.js  ${(code.length / 1024).toFixed(1)}kb (ES5, Chromium ${TV_TARGET_CHROME}+)`);
}
