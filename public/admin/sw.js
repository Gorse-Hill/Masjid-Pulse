// Masjid Pulse Admin service worker: caches the app shell so the PWA opens offline.
// API calls are never cached (admins must always see live data).
const CACHE = 'mp-admin-v4';
const SHELL = [
  '/admin/',
  '/admin/app.js',
  '/admin/styles.css',
  '/admin/manifest.webmanifest',
  '/icons/icon-192.png',
  '/brand/tv-emblem.png',
];

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches
      .open(CACHE)
      .then((c) => c.addAll(SHELL))
      .then(() => self.skipWaiting()),
  );
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.pathname.startsWith('/api/')) return;
  // Network first, fall back to cache.
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        if (res.ok && url.origin === self.location.origin) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(e.request, copy));
        }
        return res;
      })
      .catch(() => caches.match(e.request).then((r) => r || caches.match('/admin/'))),
  );
});
